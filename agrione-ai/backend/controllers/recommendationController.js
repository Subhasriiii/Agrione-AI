const Prediction = require('../models/Prediction');

const CROP_INFERENCE_URL = process.env.CROP_INFERENCE_URL || 'http://127.0.0.1:8000/predict';
const MODEL_INPUTS = [
  { field: 'nitrogen', name: 'N', min: 0, max: 140 },
  { field: 'phosphorus', name: 'P', min: 5, max: 145 },
  { field: 'potassium', name: 'K', min: 5, max: 205 },
  { field: 'temperature', name: 'temperature', min: 8.825, max: 43.675 },
  { field: 'humidity', name: 'humidity', min: 14.258, max: 99.982 },
  { field: 'ph', name: 'ph', min: 3.505, max: 9.935 },
  { field: 'rainfall', name: 'rainfall', min: 20.211, max: 298.56 },
];

exports.getRecommendation = async (req, res) => {
  const inputs = req.body || {};
  const modelInputs = {};

  for (const { field, name, min, max } of MODEL_INPUTS) {
    const rawValue = inputs[field];
    const value = typeof rawValue === 'string' ? rawValue.trim() : rawValue;
    const numericValue = Number(value);
    if (
      (typeof value !== 'number' && typeof value !== 'string')
      || value === ''
      || !Number.isFinite(numericValue)
      || numericValue < min
      || numericValue > max
    ) {
      return res.status(400).json({
        success: false,
        message: `Invalid crop recommendation input: ${field} must be a number between ${min} and ${max}.`,
      });
    }

    modelInputs[name] = numericValue;
  }

  let response;
  try {
    response = await fetch(CROP_INFERENCE_URL, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(modelInputs),
      signal: AbortSignal.timeout(120000),
    });
  } catch (error) {
    return res.status(503).json({
      success: false,
      message: 'Crop prediction service is unavailable. Ensure the Python inference API is running.',
    });
  }

  let prediction;
  try {
    prediction = await response.json();
  } catch (error) {
    return res.status(502).json({
      success: false,
      message: 'Crop prediction service returned an invalid response.',
    });
  }

  if (!response.ok) {
    if (response.status === 422) {
      return res.status(400).json({
        success: false,
        message: "One or more values are outside the trained model's supported range.",
      });
    }
    return res.status(502).json({
      success: false,
      message: 'Crop prediction service failed to generate a prediction.',
    });
  }

  if (
    prediction?.success !== true
    || typeof prediction.predictedCrop !== 'string'
    || !prediction.predictedCrop.trim()
    || typeof prediction.probability !== 'number'
    || !Number.isFinite(prediction.probability)
    || prediction.probability < 0
    || prediction.probability > 100
    || typeof prediction.modelType !== 'string'
    || !prediction.modelType.trim()
    || prediction.modelStatus !== 'trained_ml_model'
  ) {
    return res.status(502).json({
      success: false,
      message: 'Crop prediction service returned an invalid prediction.',
    });
  }

  const recommendations = [{
    crop: prediction.predictedCrop,
    confidence: prediction.probability,
    probability: prediction.probability,
    modelType: prediction.modelType,
  }];
  const result = {
    predictedCrop: prediction.predictedCrop,
    probability: prediction.probability,
    modelType: prediction.modelType,
    recommendations,
    modelStatus: 'trained_ml_model',
  };

  try {
    await Prediction.create({
      user: req.user._id,
      farm: inputs.farmId || undefined,
      type: 'crop_recommendation',
      inputs,
      result,
      confidence: prediction.probability,
      isBaseline: false,
      modelStatus: 'trained_ml_model',
    });
  } catch (error) {
    return res.status(500).json({
      success: false,
      message: 'Crop prediction succeeded, but could not be saved to history.',
    });
  }

  return res.json({
    success: true,
    recommendations,
    modelStatus: 'trained_ml_model',
    disclaimer: 'This recommendation is generated by a trained ML model. Validate recommendations with field trials and local extension guidance.',
  });
};
